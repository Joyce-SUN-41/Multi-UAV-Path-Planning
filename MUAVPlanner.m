function runPlanner(~,~)
    set(statusL,'Text','?????CA ?????????????');
    drawnow;
    % ???????
    if strcmp(modeDD.Value,'TOUR ???'), mode='tour'; else mode='p2p'; end
    % ??????
    ddv = diffDD.Value;
    if strcmp(ddv,'?3?/???? (easy)'), diff='easy';
    elseif strcmp(ddv,'?????? (hard)'), diff='hard';
    else diff='medium'; end
    nUAV = nUAVEd.Value; nCtrl = nCtrlEd.Value;
    pop = popEd.Value; iter = iterEd.Value; maxFE = maxFEEd.Value;
    wObs = wObsEd.Value; wSm = wSmEd.Value; wSep = wSepEd.Value; wLen = wLenEd.Value;

    % ?????????????????????
    if strcmp(mode,'tour')
        scene = mu_config('tour','nUAV',nUAV,'difficulty',diff,'seed',2);
    else
        scene = mu_config('p2p','nUAV',nUAV,'nCtrl',nCtrl,'difficulty',diff,'seed',2);
    end
    scene.w.obstacle   = wObs;
    scene.w.smooth     = wSm;
    scene.w.separation = wSep;
    scene.w.length     = wLen;
    % ???E??????????????????????? UAV ????????????????
    if isfield(APP,'commsLinkChk') && APP.commsLinkChk.Value
        scene.w.comms = 30;   % ?????????? w.obstacle ?????
    else
        scene.w.comms = 0;
    end

    try
        [bx, bc, cv, trajs, sc] = mu_run_planner(mode, ...
            'pop',pop,'iter',iter,'maxFE',maxFE,'nUAV',nUAV, ...
            'difficulty',diff,'nCtrl',nCtrl,'seed',2);
    catch ME
        set(statusL,'Text',['???????' ME.message]);
        return;
    end

    APP.scene = sc; APP.trajs = trajs; APP.bestX = bx;
    APP.curve = cv; APP.bestCost = bc; APP.mode = mode;

    % ???????penetration = ???????>=0 ????????>0 ????????????
    mp = 0;
    for k=1:numel(trajs)
        [~,o] = mu_obstacle_dist(trajs{k}, sc.obstacles, 0);
        mp = max(mp, -min(o));   % ?????????dist<0 ??????
    end
    % ????
    drawScene();
    cla(axC); hold(axC,'on'); grid(axC,'on');
    semilogy(axC, cv, 'Color',C_ACCENT, 'LineWidth',1.6);
    title(axC,'CA ????????','Color',C_ACCENT);
    xlabel(axC,'????'); ylabel(axC,'???? (log)');
    % ???????????
    ot = {sc.obstacles.type};
    nB = sum(strcmp(ot,'bldg')); nTw = sum(strcmp(ot,'tower'));
    nNf = sum(strcmp(ot,'nofly')); nTr = sum(strcmp(ot,'tree'));
    nWt = sum(strcmp(ot,'water')); tOn = ~isempty(sc.terrainF);
    set(infoL,'Text',sprintf('??????%s/%s  ???????%d  :%d ??:%d ????:%d ??:%d ?:%d ????:%d  ?????%.2f  ?????%.3f', ...
        mode, diff, nUAV, nB, nTw, nNf, nTr, nWt, tOn, bc, mp));
    set(statusL,'Text',sprintf('???%s/%s ??????????????? %.2f??????????? %.3f??0 ???????????????', ...
        diffLabel4(diff), mode, bc, mp));
    set(animBtn,'Enable','on');
    set(exportBtn,'Enable','on');
    drawnow;
end

function exportImg(~,~)
    % ?? exportgraphics ???? UIAxes??print/saveas ?? uiaxes ??????????????
    % ?????????? results/ ??????????????????????????????????
    if isempty(APP.trajs) || isempty(APP.scene)
        set(statusL,'Text','??????????????????????');
        return;
    end
    % results ???????? demo ???????
    appDir = fileparts(mfilename('fullpath'));
    outDir = fullfile(appDir, 'results');
    if ~exist(outDir,'dir'), mkdir(outDir); end
    runTS = char(datetime('now','Format','yyyy-MM-dd_HHmmSS'));
    % ??????????? + ???
    sc = APP.scene;
    tag = sprintf('%s_%s', APP.mode, sc.difficulty);
    try
        % 3D ??????PNG??? 300dpi??+ EPS??????????? .tmp ????????????
        f3 = fullfile(outDir, sprintf('muav_%s_3D_%s', tag, runTS));
        mu_save_ui(APP.ax3, [f3 '.png'], 'png');
        mu_save_ui(APP.ax3, [f3 '.eps'], 'eps');
        % ?????????PNG + EPS
        fC = fullfile(outDir, sprintf('muav_%s_convergence_%s', tag, runTS));
        mu_save_ui(APP.axC, [fC '.png'], 'png');
        mu_save_ui(APP.axC, [fC '.eps'], 'eps');
        % 同时保存完整结果为 .mat（可复现：scene + trajs + bestX + curve + APP 参数）
        res = struct();
        res.tag        = tag;
        res.mode       = APP.mode;
        res.difficulty = sc.difficulty;
        res.scene      = sc;
        res.trajs      = APP.trajs;
        res.bestX      = APP.bestX;
        res.bestCost   = APP.bestCost;
        res.curve      = APP.curve;
        res.opt        = struct('mode',APP.mode,'difficulty',sc.difficulty, ...
                                'nUAV',sc.nUAV,'nCtrl',sc.nCtrl,'seed',2);
        matF = fullfile(outDir, sprintf('muav_%s_%s.mat', tag, runTS));
        mu_save_result(res, outDir, 'tag', tag);
        % 补充视角图（俯视/侧视/近景），与已导出的 3D 透视互补，看清路径
        mu_export_views(sc, APP.trajs, APP.mode, outDir, tag, runTS, ...
            sprintf('%.2f', APP.bestCost), 'views', {'top','sideX','sideY','closeup'});
        set(statusL,'Text',sprintf('??????? results/??%s??3D + ?????? + ??PNG/EPS ??MAT??', matF));
    catch ME
        set(statusL,'Text',['????????' ME.message]);
    end
end

